class Solution {
public:
    long long countCommas(long long n) {
        if(n<=999){
            return 0;
        }
        long long ans=0;

        if(n>=1000000000000000) {
            ans += (1000000 - 999)-1;
            ans += 2 * (1000000000 - 999999-1);
            ans += 3 * (1000000000000 - 999999999-1);
            ans += 4 * (1000000000000000 - 999999999999-1);
            ans += 5 * (n - 999999999999999);
        }

         else if(n>=1000000000000) {
            ans += (1000000 - 999)-1;
            ans += 2 * (1000000000 - 999999-1);
            ans += 3 * (1000000000000 - 999999999-1);
            ans += 4 * (n - 999999999999);
        }
         else if(n >= 1000000000){
            ans += (1000000 - 999)-1;              
            ans += 2 * (1000000000 - 999999-1);
            ans += 3 * (n - 999999999);
        } 
        else if(n >= 1000000){
            ans += (1000000 - 999)-1;              
            ans += 2 * (n - 999999);            
        } 
       
        else if(n >=1000){
            ans += (n - 999);
        } 
        return ans;
    }
};